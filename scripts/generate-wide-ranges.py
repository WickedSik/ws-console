#!/usr/bin/env python3
#
# Generate core/src/main/scala/glyph/WideRanges.scala from Unicode's
# EastAsianWidth.txt.
#
# WHY THIS EXISTS
# ---------------
# `Widths.isWideCodepoint` decides how many terminal columns a glyph takes.
# It used to be a hand-picked list of blocks, which disagreed with Unicode in
# both directions: whole emoji planes counted wide although most of their
# symbols are narrow (U+2713 CHECK MARK, the U+1FB00 sextants), while wide
# emoji elsewhere (U+2615 HOT BEVERAGE, U+2B50 WHITE MEDIUM STAR) and whole
# scripts (Tangut, Nushu, CJK Extension G) counted narrow. This script derives
# the table from the Unicode data instead.
#
# Wide means East Asian Width W (Wide) or F (Fullwidth). Ambiguous (A) stays
# narrow, as in most terminals in Western locales. Unassigned code points
# inside wide blocks are listed as W by the data file itself, so ideographs
# assigned in later Unicode versions already measure wide.
#
# USAGE
#   scripts/generate-wide-ranges.py                 # download the pinned version
#   scripts/generate-wide-ranges.py EastAsianWidth.txt
#
# Bump UNICODE_VERSION to move to a newer Unicode release, rerun, and review
# the diff of the generated file.

import re
import sys
import urllib.request
from pathlib import Path

UNICODE_VERSION = "16.0.0"
SOURCE_URL = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/EastAsianWidth.txt"
TARGET = Path(__file__).resolve().parent.parent / "core/src/main/scala/glyph/WideRanges.scala"

LINE = re.compile(r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)")


def read_source(argv):
    if len(argv) > 1:
        return Path(argv[1]).read_text(encoding="utf-8")
    with urllib.request.urlopen(SOURCE_URL) as response:
        return response.read().decode("utf-8")


def wide_ranges(text):
    header = text.splitlines()[0]
    if UNICODE_VERSION not in header:
        sys.exit(f"expected EastAsianWidth for Unicode {UNICODE_VERSION}, got: {header}")
    ranges = []
    for line in text.splitlines():
        match = LINE.match(line)
        if match and match.group(3) in ("W", "F"):
            start = int(match.group(1), 16)
            end = int(match.group(2) or match.group(1), 16)
            ranges.append((start, end))
    ranges.sort()
    merged = []
    for start, end in ranges:
        if merged and start <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end))
        else:
            merged.append((start, end))
    return merged


def render(ranges):
    rows = "\n".join(f"    0x{start:04X}, 0x{end:04X}," for start, end in ranges)
    return f"""package io.github.wickedsik.wsconsole
package glyph

// GENERATED by scripts/generate-wide-ranges.py from Unicode {UNICODE_VERSION}
// EastAsianWidth.txt. Do not edit; rerun the script instead.

/**
 * Code points Unicode gives East Asian Width W (Wide) or F (Fullwidth):
 * the glyphs a terminal draws two columns wide. Read by
 * [[Widths.isWideCodepoint]].
 */
private[glyph] object WideRanges:

  /** The Unicode version the table was generated from. */
  val UnicodeVersion: String = "{UNICODE_VERSION}"

  /**
   * Inclusive `start, end` pairs, sorted and non-overlapping, with adjacent
   * ranges merged: `bounds(2 * i)` to `bounds(2 * i + 1)` is range `i`.
   */
  val bounds: Array[Int] = Array(
{rows}
  )
"""


def main(argv):
    ranges = wide_ranges(read_source(argv))
    TARGET.write_text(render(ranges), encoding="utf-8")
    print(f"{TARGET}: {len(ranges)} ranges, {sum(e - s + 1 for s, e in ranges)} code points")


if __name__ == "__main__":
    main(sys.argv)
